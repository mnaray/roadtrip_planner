// Escape user-provided text before interpolating it into HTML strings
// (innerHTML, Leaflet popups), which would otherwise execute embedded markup.
export function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;")
}
